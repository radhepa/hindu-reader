// Curated Ramayana assembler — fuzzy cross-verified.
// Sanskrit (clean, canonical refs): Bombay edition (bombay.indology.info).
// English (public domain): M. N. Dutt prose (1891–94), via the Itihāsa corpus.
// Each clean Bombay verse is paired with the Dutt English whose (OCR-noisy)
// Sanskrit is most similar (bigram-Dice). Pairs below threshold are dropped —
// nothing is guessed. Verse numbers + Sanskrit come from Bombay (canonical).
// Scope: Bala Kanda Sargas 1–SARGA_MAX (the narrative opening of the epic).

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { devanagariToIAST } from './translit.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const dataDir = join(__dirname, '..', 'assets', 'data');

const itihasa = JSON.parse(readFileSync(join(__dirname, '_itihasa_ramayana.json'), 'utf8'));
const bombayRaw = readFileSync(join(__dirname, '_bombay_ram01.txt'), 'utf8');
const current = JSON.parse(readFileSync(join(dataDir, 'ramayana.json'), 'utf8'));

const SARGA_MAX = 5;
const THRESHOLD = 0.5; // bigram-Dice; near-identical verses score ~0.8+, different ~<0.3

// Parse Bombay Bala Kanda -> sarga -> verse -> devanagari (join padas).
const bombay = new Map(); // "sarga.verse" -> [lines]
for (const line of bombayRaw.split('\n')) {
  const m = line.match(/^(\d)(\d{3})(\d{3})([a-z])\s+(.+)$/);
  if (!m || m[1] !== '1') continue;
  const key = `${Number(m[2])}.${Number(m[3])}`;
  if (!bombay.has(key)) bombay.set(key, []);
  bombay.get(key).push(m[5].trim());
}

// Normalization for fuzzy matching only (display uses exact Bombay text).
function normMatch(s) {
  return s
    .replace(/[शष]/g, 'स')        // fold sibilants
    .replace(/[ङञणनम]्/g, '')      // conjunct nasal -> drop
    .replace(/[ंःँ्ॐऽ]/g, '')      // anusvara/visarga/candrabindu/virama/praṇava/avagraha
    .replace(/[०-९।॥\s]/g, '')      // digits/dandas/space
    .replace(/(.)\1+/g, '$1');     // collapse gemination
}

function bigrams(s) {
  const g = new Map();
  for (let i = 0; i < s.length - 1; i++) {
    const b = s.slice(i, i + 2);
    g.set(b, (g.get(b) || 0) + 1);
  }
  return g;
}
function dice(a, b) {
  if (!a.length || !b.length) return 0;
  const ga = bigrams(a), gb = bigrams(b);
  let inter = 0, na = 0, nb = 0;
  for (const v of ga.values()) na += v;
  for (const v of gb.values()) nb += v;
  for (const [k, v] of ga) if (gb.has(k)) inter += Math.min(v, gb.get(k));
  return (2 * inter) / (na + nb);
}

const SOURCE = {
  sanskrit_translator: 'Bombay edition (Vālmīki Rāmāyaṇa, bombay.indology.info)',
  english_translator: 'Manmatha Nath Dutt',
  edition: 'Sanskrit: Bombay recension (public domain). English: M. N. Dutt prose, 1891–1894 (public domain).',
  english_via: 'Itihāsa corpus (Aralikatte et al., WAT2021), shloka-aligned',
  transliteration: 'Mechanical IAST generated by scripts/translit.mjs',
  cross_check: 'Bombay clean Sanskrit fuzzy-matched (bigram-Dice ≥ ' + THRESHOLD + ') to Dutt/Itihāsa Sanskrit; verse number + Sanskrit from Bombay',
  verified: true,
};

const tidyEnglish = (s) => String(s).replace(/\s+([.,;:!?])/g, '$1').replace(/\s{2,}/g, ' ').trim();

const SARGA_NAMES = { 1: 'Samkshepa Ramayana', 2: 'The Origin of the Sloka' };

const verses = [];
let totalBombay = 0, totalShipped = 0, lowScore = [];

for (let sarga = 1; sarga <= SARGA_MAX; sarga++) {
  const rec = itihasa['vol-i'][sarga - 1];
  if (!rec || rec.chapter !== String(sarga)) {
    console.error(`Itihāsa vol-i index for sarga ${sarga} mismatch (chapter=${rec?.chapter}) — skipping`);
    continue;
  }
  // Bombay verses of this sarga, ordered.
  const bVerses = [...bombay.keys()]
    .filter((k) => Number(k.split('.')[0]) === sarga)
    .map((k) => ({ verse: Number(k.split('.')[1]), dev: bombay.get(k).join('\n') }))
    .sort((a, b) => a.verse - b.verse);
  totalBombay += bVerses.length;

  // Precompute normalized forms.
  const bNorm = bVerses.map((b) => normMatch(b.dev));
  const iNorm = rec.sn.map((s) => normMatch(s));

  // All candidate pairs above threshold, then greedy assign by descending score.
  const pairs = [];
  for (let bi = 0; bi < bVerses.length; bi++)
    for (let ii = 0; ii < rec.sn.length; ii++) {
      const d = dice(bNorm[bi], iNorm[ii]);
      if (d >= THRESHOLD) pairs.push([d, bi, ii]);
    }
  pairs.sort((a, b) => b[0] - a[0]);
  const usedB = new Set(), usedI = new Set();
  const assign = new Map(); // bi -> {ii, score}
  for (const [d, bi, ii] of pairs) {
    if (usedB.has(bi) || usedI.has(ii)) continue;
    usedB.add(bi); usedI.add(ii); assign.set(bi, { ii, score: d });
  }

  for (let bi = 0; bi < bVerses.length; bi++) {
    const a = assign.get(bi);
    if (!a) continue; // no English match -> drop (don't guess)
    if (a.score < 0.62) lowScore.push(`${sarga}.${bVerses[bi].verse} (dice ${a.score.toFixed(2)})`);
    const dev = bVerses[bi].dev;
    verses.push({
      id: `ramayana_1_${sarga}_${bVerses[bi].verse}`,
      book: 'ramayana',
      kanda: 1,
      kanda_name: 'Bala Kanda',
      sarga,
      sarga_name: SARGA_NAMES[sarga] || `Sarga ${sarga}`,
      verse: bVerses[bi].verse,
      sanskrit: dev,
      transliteration: devanagariToIAST(dev),
      translations: { english: tidyEnglish(rec.en[a.ii]) },
      explanations: {},
      daily_quote_eligible: sarga === 1 && bVerses[bi].verse === 1,
      holiday_tags: [],
      source: SOURCE,
    });
    totalShipped++;
  }
}

verses.sort((a, b) => (a.sarga - b.sarga) || (a.verse - b.verse));

const chapters = current.chapters.map((c) => ({ ...c, verse_count: c.number === 1 ? verses.length : 0 }));
const meta = { ...current.meta, subtitle: 'Curated · Bala Kanda (opening sargas)', total_verses: verses.length };
writeFileSync(join(dataDir, 'ramayana.json'), JSON.stringify({ meta, chapters, verses }, null, 2) + '\n');
JSON.parse(readFileSync(join(dataDir, 'ramayana.json'), 'utf8'));

console.log(`Bala Kanda sargas 1–${SARGA_MAX}: Bombay verses ${totalBombay}, SHIPPED (cross-verified) ${totalShipped}`);
const perSarga = {};
for (const v of verses) perSarga[v.sarga] = (perSarga[v.sarga] || 0) + 1;
console.log('per-sarga shipped:', JSON.stringify(perSarga));
console.log('low-confidence pairs (dice<0.62) to spot-check:', lowScore.length, lowScore.slice(0, 15).join('; '));
